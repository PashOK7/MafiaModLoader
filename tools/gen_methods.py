"""gen_methods.py: the bridge methods' help, from docs/PROTOCOL.md into host/methods.inc.

    python tools/gen_methods.py           write host/methods.inc
    python tools/gen_methods.py --check   exit 1 when host/methods.inc is not what PROTOCOL.md gives

docs/PROTOCOL.md's tables are the one description of the host's methods: each row `| `name` | params | result |`.
The host lists every one of them in `commands.list` with its params, its result and the thread that answers it
(the bridge's at once, or the game's at its next frame), so an agent finds a method and how to call it without
the document. tests/run_tests.py runs the check and calls every method listed, so a method documented and not
answered, or answered and not documented, fails the tests.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, 'docs', 'PROTOCOL.md')
OUT = os.path.join(ROOT, 'host', 'methods.inc')


def cells(line):
    # a table row's cells: split on | that is not escaped (\|)
    parts = re.split(r'(?<!\\)\|', line.strip())[1:-1]
    return [p.strip().replace('\\|', '|') for p in parts]


def rows():
    out = []
    thread = None
    for line in open(DOC, encoding='utf-8'):
        if line.startswith('## '):
            thread = 'bridge' if 'at once' in line else 'game' if 'game thread' in line else None
            continue
        if thread is None or not line.startswith('| `'):
            continue
        c = cells(line)
        if len(c) != 3:
            continue
        for name in re.findall(r'`([a-z0-9_.]+)`', c[0]):
            out.append((name, thread, c[1], c[2]))
    return out


def lit(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def text():
    lines = ['// Generated by tools/gen_methods.py from docs/PROTOCOL.md: do not edit (edit the document, run the tool).',
             '// {name, thread ("bridge": answered at once; "game": at the game\'s next frame), params, result}']
    for name, thread, params, result in rows():
        lines.append('{%s, %s, %s, %s},' % (lit(name), lit(thread), lit(params), lit(result)))
    return '\n'.join(lines) + '\n'


def main(argv):
    want = text()
    have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    if '--check' in argv:
        if have != want:
            print('host/methods.inc is not what docs/PROTOCOL.md gives: run python tools/gen_methods.py')
            return 1
        print('host/methods.inc: current (%d methods)' % len(rows()))
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(want)
    print('host/methods.inc: %d methods' % len(rows()))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
